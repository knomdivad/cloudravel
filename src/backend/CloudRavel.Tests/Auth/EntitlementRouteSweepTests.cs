    public static IEnumerable<object[]> AllRoutes()
    {
        foreach (var route in HttpRouteDiscovery.DiscoverSweepRoutes())
            yield return new object[] { route.Method, route.RouteTemplate };
    }

    [Fact]
    public void Route_catalog_covers_every_discovered_http_route()
    {
        var discovered = HttpRouteDiscovery.DiscoverAll();
        var sweep = HttpRouteDiscovery.DiscoverSweepRoutes();
        Assert.Equal(70, RouteEntitlementCatalog.AllRouteMappings.Count);
        Assert.Equal(83, sweep.Count);

        var unmapped = discovered.Where(r =>
            RouteEntitlementCatalog.ResolveRequirement(HttpRouteDiscovery.MaterializePath(r.Item2), r.Item1) is null).ToList();
        Assert.True(unmapped.Count == 0, "Unmapped: " + string.Join(", ", unmapped.Select(u => $"{u.Item1} {u.Item2}")));
    }

    [Theory]
    [MemberData(nameof(AllRoutes))]
    public async Task Middleware_pipeline_matches_persona_matrix(string method, string routeTemplate)
    {
        var path = HttpRouteDiscovery.MaterializePath(routeTemplate);
        var requirement = RouteEntitlementCatalog.ResolveRequirement(path, method)!;

        foreach (var persona in Personas.All)
        {
            var host = new EntitlementMiddlewarePipelineHost(persona.Member, persona.Org, persona.SystemAdmin);
            var (status, next, _) = await host.InvokeAsync(method, path);
            var expectedAllow = EntitlementExpectations.MiddlewareAllows(requirement, persona);

            if (expectedAllow)
            {
                Assert.True(next, $"{persona.Name} should pass middleware for {method} {routeTemplate}");
            }
            else
            {
                Assert.False(next, $"{persona.Name} should be blocked for {method} {routeTemplate}");
                Assert.Equal(HttpStatusCode.Forbidden, status);
            }
        }
    }

    [Fact]
    public async Task Write_entitlement_matrix_markdown()
    {
        var rows = new List<string>();
        rows.Add("# Entitlement route matrix");
        rows.Add("");
        rows.Add("Generated by `EntitlementRouteSweepTests` against the real TenantContext + FeatureRouteEntitlement middleware pipeline.");
        rows.Add("");
        rows.Add("| Route | Method | Requirement | Bot-only | Cloud-only | Both | Handler gate | Field leak |");
        rows.Add("| --- | --- | --- | --- | --- | --- | --- | --- |");

        foreach (var (method, routeTemplate) in HttpRouteDiscovery.DiscoverSweepRoutes())
        {
            var path = HttpRouteDiscovery.MaterializePath(routeTemplate);
            var requirement = RouteEntitlementCatalog.ResolveRequirement(path, method)!;
            var cells = new List<string>();
            var leakMarks = new List<string>();
            var gateMarks = new List<string>();
            foreach (var persona in Personas.All)
            {
                var host = new EntitlementMiddlewarePipelineHost(persona.Member, persona.Org, persona.SystemAdmin);
                var (status, next, _) = await host.InvokeAsync(method, path);
                var allowed = EntitlementExpectations.MiddlewareAllows(requirement, persona);
                var code = allowed ? (next ? "200" : "blocked") : (status?.ToString() ?? "403");
                cells.Add(code);

                var sweep = await EntitlementSweepResponseRunner.GetResponseAsync(persona, method, routeTemplate);
                var verdict = PersonaFieldLeakAssertions.Evaluate(persona.Name, sweep.Body);
                var label = persona.Name switch
                {
                    "bot-only" => "bot",
                    "cloud-only" => "cloud",
                    _ => "both",
                };
                leakMarks.Add($"{label}:{verdict}");
                gateMarks.Add($"{label}:{sweep.HandlerGate}");
            }

            rows.Add($"| `{routeTemplate}` | {method} | {requirement} | {cells[0]} | {cells[1]} | {cells[2]} | {string.Join("|", gateMarks)} | {string.Join("|", leakMarks)} |");
        }

        var repoRoot = LocateRepoRoot();
        var outPath = Path.Combine(repoRoot, "docs", "bot-monitor", "entitlement-matrix.md");
        Directory.CreateDirectory(Path.GetDirectoryName(outPath)!);
        await File.WriteAllTextAsync(outPath, string.Join('\n', rows) + '\n', Encoding.UTF8);
        Assert.True(File.Exists(outPath));
    }

    [Fact]
    public async Task Get_tenants_without_workspace_header_is_bad_request()
    {
        var persona = Personas.CloudOnly;
        var host = new EntitlementMiddlewarePipelineHost(persona.Member, persona.Org);
        var (status, next, _) = await host.InvokeAsync("GET", "/api/tenants", sendTenantHeader: false);
        Assert.False(next);
        Assert.Equal(HttpStatusCode.BadRequest, status);
    }

    public static IEnumerable<object[]> AllPersonaRoutePairs()
    {
        foreach (var route in AllRoutes())
        {
            var method = (string)route[0];
            var template = (string)route[1];
            foreach (var persona in Personas.All)
                yield return new object[] { persona.Name, method, template };
        }
    }

    [Theory]
    [MemberData(nameof(AllPersonaRoutePairs))]
    public async Task Field_leak_sweep_all_routes_all_personas(string personaName, string method, string routeTemplate)
    {
        var persona = Personas.All.Single(p => p.Name == personaName);
        var json = await EntitlementSweepResponseRunner.GetResponseBodyAsync(persona, method, routeTemplate);
        PersonaFieldLeakAssertions.AssertNoLeak(personaName, routeTemplate, method, json);
    }

    [Fact]
    public async Task Organization_list_omits_cloud_fields_without_cloud_entitlement()
    {
        var orgId = Guid.NewGuid();
        var userId = Guid.NewGuid();
        var orgRepo = Substitute.For<IOrganizationRepository>();
        orgRepo.GetAllAsync().Returns(new List<Organization>
        {
            new() { OrgId = orgId, Name = "Acme", Status = "active", Environment = "Development" },
        });
        orgRepo.GetFeatureEntitlementsAsync(orgId).Returns(new FeatureEntitlements(true, false));

        var userRepo = Substitute.For<IUserRepository>();
        userRepo.GetUserTenantAccessAsync(userId).Returns(new List<UserTenantAccess>
        {
            new() { TenantId = orgId, Role = OrgRole.ReadOnly, UserId = userId },
        });
        userRepo.GetFeatureEntitlementsAsync(userId, orgId).Returns(new FeatureEntitlements(true, false));

        var fn = new OrganizationFunctions(
            orgRepo,
            Substitute.For<ITenantRepository>(),
            Substitute.For<ICloudOrgRepository>(),
            Substitute.For<ICloudAccountRepository>(),
            userRepo,
            Substitute.For<IInventoryCollectionService>(),
            Substitute.For<IPlatformInfo>(),
            NullLogger<OrganizationFunctions>.Instance);

        var ctx = new Assessment.TestFunctionContext();
        ctx.Items["SystemRole"] = SystemRole.Member;
        ctx.SetUser(userId);
        var req = new FakeHttpRequestData(ctx, "GET", null, "http://localhost:7071/api/organizations");
        ctx.SetRequest(req);

        var res = await fn.ListOrganizations(req, ctx);
        var json = await res.ReadBodyAsync();
        Assert.DoesNotContain("cloudCount", json, StringComparison.OrdinalIgnoreCase);
        Assert.DoesNotContain("azureConnected", json, StringComparison.OrdinalIgnoreCase);
        Assert.DoesNotContain("resourceCount", json, StringComparison.OrdinalIgnoreCase);
        Assert.Contains("callerRole", json, StringComparison.OrdinalIgnoreCase);
    }

    private static string LocateRepoRoot()
    {
        var dir = new DirectoryInfo(AppContext.BaseDirectory);
        while (dir != null)
        {
            if (File.Exists(Path.Combine(dir.FullName, "CloudRavel.sln")))
                return dir.FullName;
            dir = dir.Parent;
        }

        throw new InvalidOperationException("Repo root not found.");
    }

    internal sealed record Persona(string Name, FeatureEntitlements Member, FeatureEntitlements Org, bool SystemAdmin);

    internal static class Personas
    {
        public static Persona BotOnly { get; } = new("bot-only", new FeatureEntitlements(true, false), new FeatureEntitlements(true, false), false);
        public static Persona CloudOnly { get; } = new("cloud-only", new FeatureEntitlements(false, true), new FeatureEntitlements(false, true), false);
        public static Persona Both { get; } = new("both", FeatureEntitlements.Both, FeatureEntitlements.Both, false);
        public static IReadOnlyList<Persona> All { get; } = new[] { BotOnly, CloudOnly, Both };
    }

    internal static class EntitlementExpectations
    {
        public static bool MiddlewareAllows(string requirement, Persona persona)
        {
            if (persona.SystemAdmin) return true;
            return requirement switch
            {
                RouteEntitlementCatalog.RequirementAuthenticated => true,
                RouteEntitlementCatalog.RequirementCloudMonitoring => persona.Member.CloudMonitoring && persona.Org.CloudMonitoring,
                RouteEntitlementCatalog.RequirementBotMonitoring => persona.Member.BotMonitoring && persona.Org.BotMonitoring,
                _ => false,
            };
        }
    }

}
